export function getInitialLang(): Lang {
  const saved = localStorage.getItem('metronome_lang') as Lang | null;
  if (saved === 'ja' || saved === 'en') return saved;
  return navigator.language.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}
